/**
 * Xiaomi Weather's city table, grouped by province in the original row order. Each line of a
 * province block is `city[.district]:cityNum`.
 */
val WEATHER_CITIES: List<WeatherCity> by lazy {
    CITY_PROVINCES.flatMap { province ->
        province.entries.lineSequence().map { line ->
            val (name, cityNum) = line.split(':')
            WeatherCity(
                countryCode = province.countryCode,
                province = province.name,
                city = name.substringBefore('.'),
                district = name.substringAfter('.', "").ifEmpty { null },
                cityNum = cityNum,
            )
        }.toList()
    }
}

